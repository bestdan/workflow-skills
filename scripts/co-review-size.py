#!/usr/bin/env python3
"""Measure how much of a diff a reviewer actually has to read, for co-review step 6.

Usage:
  python3 co-review-size.py --diff <unified-diff-file> [--root <repo>] [--no-attrs]
                            [--max-lines N] [--max-files N] [--prose-lines N]

Prints one JSON object on stdout:

  {"reviewable": {"lines", "files", "code_lines", "test_lines", "prose_lines"},
   "generated":  {"lines", "files", "paths": [{"path", "lines", "reason"}]},
   "groups":     [{"kind", "area", "lines", "files", "paths"}],   # largest first
   "thresholds": {"max_lines", "max_files", "prose_lines"},
   "too_big": bool, "too_big_reasons": [str],
   "prose_split": bool}

A line is an added or deleted line; context lines are not counted. Generated
files are excluded from every `reviewable` count: nobody reads a lockfile or a
protobuf stub line by line, so counting one would let a regenerated lockfile
trip the gate on a one-line change. A file is generated when any of these hold:

  - its path matches `GENERATED` in scripts/local-review/server.py, or one of
    the extra lockfile names below;
  - `git check-attr linguist-generated` reports it `set` / `true` under `--root`
    (skipped with `--no-attrs`, or when `--root` is not a git checkout);
  - one of the file's first five lines, where the diff shows them, carries a generator marker
    (`@generated`, `DO NOT EDIT`, `Generated by`; case-sensitive, and Go's
    `Code generated ... DO NOT EDIT` header matches on its second half).

`too_big` is the size gate: reviewable lines above `--max-lines` or reviewable
files above `--max-files`. `prose_split` flags the mixed case the gate misses:
at least `--prose-lines` of prose next to code or tests, which is a candidate
split unit by default because prose needs a different review from code. Both
are inputs to step 6's judgment, never the verdict itself.

Reuses `parse_diff()` from scripts/local-review/server.py, loaded by file path
the same way scripts/diff-anchor-check.py does (its module body has no side
effects; see that script's docstring).

Exit codes: 0 measured; 2 usage error or unreadable diff.
"""

import argparse
import importlib.util
import json
import os
import re
import subprocess
import sys

DEFAULT_MAX_LINES = 800
DEFAULT_MAX_FILES = 30
DEFAULT_PROSE_LINES = 300

EXTRA_GENERATED = re.compile(
    r"(^|/)(pnpm-lock\.yaml|npm-shrinkwrap\.json|Package\.resolved|pubspec\.lock)$"
)
MARKER = re.compile(r"@generated|DO NOT EDIT|Generated by")
PROSE = re.compile(r"\.(md|mdx|markdown|rst|txt|adoc)$", re.IGNORECASE)
TEST = re.compile(
    r"(^|/)(tests?|__tests__|spec|testdata|fixtures?)/"
    r"|(^|/)(test_[^/]*|[^/]*_test\.[^/]+|[^/]*\.(test|spec)\.[^/]+|test-[^/]*\.sh)$"
)


def _load_server():
    path = os.path.join(
        os.path.dirname(os.path.abspath(__file__)), "local-review", "server.py"
    )
    spec = importlib.util.spec_from_file_location("_co_review_size_server", path)
    assert spec is not None and spec.loader is not None, f"cannot load {path}"
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _added_head(f, n=5):
    """Lines of the new file's first `n` that the diff shows, added or context."""
    out = []
    for hunk in f["hunks"]:
        for row in hunk["rows"]:
            r = row["r"]
            if r.get("t") in ("add", "ctx") and r["n"] <= n:
                out.append(r["s"])
    return out


def attr_generated(paths, root):
    """Paths `git check-attr` marks linguist-generated under `root`; empty when git can't answer."""
    if not paths:
        return set()
    try:
        out = subprocess.run(
            ["git", "-C", root, "check-attr", "-z", "linguist-generated", "--stdin"],
            input="\0".join(paths) + "\0",
            capture_output=True,
            text=True,
        )
    except OSError:
        return set()
    if out.returncode != 0:
        return set()
    fields = out.stdout.split("\0")
    marked = set()
    for i in range(0, len(fields) - 2, 3):
        path, _attr, value = fields[i], fields[i + 1], fields[i + 2]
        if value in ("set", "true"):
            marked.add(path)
    return marked


def kind_of(path):
    if PROSE.search(path):
        return "prose"
    if TEST.search(path):
        return "test"
    return "code"


def area_of(path):
    parts = path.split("/")[:-1]
    return "/".join(parts[:2]) if parts else "."


def measure(files, generated_pattern, attr_marked, max_lines, max_files, prose_lines):
    reviewable = {
        "lines": 0,
        "files": 0,
        "code_lines": 0,
        "test_lines": 0,
        "prose_lines": 0,
    }
    gen_paths: list = []
    gen_lines = 0
    groups: dict = {}
    for f in files:
        path = f["new"] if f["new"] and f["new"] != "/dev/null" else f["old"]
        lines = f["adds"] + f["dels"]
        reason = None
        if generated_pattern.search(path) or EXTRA_GENERATED.search(path):
            reason = "path"
        elif path in attr_marked:
            reason = "linguist-generated"
        elif any(MARKER.search(s) for s in _added_head(f)):
            reason = "header"
        if reason:
            gen_lines += lines
            gen_paths.append({"path": path, "lines": lines, "reason": reason})
            continue
        kind = kind_of(path)
        reviewable["lines"] += lines
        reviewable["files"] += 1
        reviewable[f"{kind}_lines"] += lines
        g = groups.setdefault(
            (kind, area_of(path)), {"lines": 0, "files": 0, "paths": []}
        )
        g["lines"] += lines
        g["files"] += 1
        g["paths"].append(path)

    reasons = []
    if reviewable["lines"] > max_lines:
        reasons.append(f"{reviewable['lines']} reviewable lines > {max_lines}")
    if reviewable["files"] > max_files:
        reasons.append(f"{reviewable['files']} reviewable files > {max_files}")
    other = reviewable["code_lines"] + reviewable["test_lines"]
    return {
        "reviewable": reviewable,
        "generated": {"lines": gen_lines, "files": len(gen_paths), "paths": gen_paths},
        "groups": [
            {"kind": k, "area": a, **g}
            for (k, a), g in sorted(
                groups.items(), key=lambda kv: (-kv[1]["lines"], kv[0])
            )
        ],
        "thresholds": {
            "max_lines": max_lines,
            "max_files": max_files,
            "prose_lines": prose_lines,
        },
        "too_big": bool(reasons),
        "too_big_reasons": reasons,
        "prose_split": reviewable["prose_lines"] >= prose_lines and other > 0,
    }


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--diff", required=True)
    ap.add_argument(
        "--root", default=".", help="git checkout whose .gitattributes to consult"
    )
    ap.add_argument("--no-attrs", action="store_true")
    ap.add_argument("--max-lines", type=int, default=DEFAULT_MAX_LINES)
    ap.add_argument("--max-files", type=int, default=DEFAULT_MAX_FILES)
    ap.add_argument("--prose-lines", type=int, default=DEFAULT_PROSE_LINES)
    args = ap.parse_args(argv)
    try:
        with open(args.diff, encoding="utf-8", errors="replace") as fh:
            text = fh.read()
    except OSError as e:
        print(f"co-review-size: cannot read {args.diff}: {e}", file=sys.stderr)
        return 2
    server = _load_server()
    files = server.parse_diff(text)
    paths = [
        f["new"] if f["new"] and f["new"] != "/dev/null" else f["old"] for f in files
    ]
    marked = set() if args.no_attrs else attr_generated(paths, args.root)
    result = measure(
        files,
        server.GENERATED,
        marked,
        args.max_lines,
        args.max_files,
        args.prose_lines,
    )
    print(json.dumps(result, indent=2))
    return 0


if __name__ == "__main__":
    sys.exit(main())
