#!/usr/bin/env python3
"""Hermetic tests for scripts/co-review-size.py.

Drives `measure()` on parsed diffs, plus one `main()` run against a temporary
git checkout so the `.gitattributes` path is exercised for real. The fixture
pins GIT_CONFIG_GLOBAL=/dev/null, per AGENTS.md.
"""

import contextlib
import importlib.util
import io
import json
import os
import subprocess
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SCRIPT = ROOT / "scripts" / "co-review-size.py"

_spec = importlib.util.spec_from_file_location("co_review_size", SCRIPT)
assert _spec is not None and _spec.loader is not None, f"cannot load {SCRIPT}"
size = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(size)
SERVER = size._load_server()


def file_diff(path, lines, first=None, new=True):
    """A unified diff adding `lines` lines to `path`; `first` replaces line 1."""
    body = [
        first if (first is not None and i == 0) else f"line {i}" for i in range(lines)
    ]
    header = [f"diff --git a/{path} b/{path}"]
    if new:
        header += ["new file mode 100644", "--- /dev/null"]
    else:
        header += [f"--- a/{path}"]
    header += [f"+++ b/{path}", f"@@ -0,0 +1,{lines} @@"]
    return "\n".join(header + ["+" + b for b in body]) + "\n"


def run(diff, attrs=frozenset(), **kw):
    files = SERVER.parse_diff(diff)
    opts = {"max_lines": 800, "max_files": 30, "prose_lines": 300}
    opts.update(kw)
    return size.measure(files, SERVER.GENERATED, set(attrs), **opts)


class MeasureTest(unittest.TestCase):
    def test_lockfile_and_stub_are_excluded(self):
        diff = (
            file_diff("src/app.py", 10)
            + file_diff("uv.lock", 900)
            + file_diff("web/pnpm-lock.yaml", 400)
            + file_diff("api/foo.pb.go", 300)
        )
        r = run(diff)
        self.assertEqual(r["reviewable"]["lines"], 10)
        self.assertEqual(r["reviewable"]["files"], 1)
        self.assertEqual(r["generated"]["files"], 3)
        self.assertEqual(r["generated"]["lines"], 1600)
        self.assertFalse(r["too_big"], "generated lines must not trip the gate")

    def test_header_marker_excludes(self):
        diff = file_diff("docs/out.md", 500, first="<!-- Generated by build.py. -->")
        r = run(diff)
        self.assertEqual(r["reviewable"]["lines"], 0)
        self.assertEqual(r["generated"]["paths"][0]["reason"], "header")

    def test_linguist_attr_excludes(self):
        r = run(file_diff("schema/api.ts", 50), attrs={"schema/api.ts"})
        self.assertEqual(r["generated"]["paths"][0]["reason"], "linguist-generated")

    def test_too_big_by_lines_and_files(self):
        diff = "".join(file_diff(f"src/m{i}.py", 30) for i in range(31))
        r = run(diff)
        self.assertTrue(r["too_big"])
        self.assertEqual(len(r["too_big_reasons"]), 2)

    def test_under_threshold_is_not_too_big(self):
        r = run(file_diff("src/a.py", 800))
        self.assertFalse(r["too_big"])

    def test_prose_next_to_code_is_a_split_candidate(self):
        diff = file_diff("scripts/model.py", 200) + file_diff(
            "dev_docs/decisions/d1.md", 300
        )
        r = run(diff)
        self.assertTrue(r["prose_split"])
        self.assertEqual(r["reviewable"]["prose_lines"], 300)
        self.assertEqual(r["reviewable"]["code_lines"], 200)

    def test_prose_only_is_not_a_split_candidate(self):
        r = run(file_diff("docs/guide.md", 900))
        self.assertFalse(r["prose_split"])

    def test_groups_by_kind_and_area_largest_first(self):
        diff = (
            file_diff("scripts/a.py", 10)
            + file_diff("scripts/test_a.py", 40)
            + file_diff("dev_docs/decisions/x.md", 20)
            + file_diff("dev_docs/decisions/y.md", 25)
        )
        groups = run(diff)["groups"]
        self.assertEqual(
            [(g["kind"], g["area"], g["lines"]) for g in groups],
            [
                ("prose", "dev_docs/decisions", 45),
                ("test", "scripts", 40),
                ("code", "scripts", 10),
            ],
        )

    def test_deleted_file_counts_under_old_path(self):
        diff = (
            "diff --git a/old.py b/old.py\ndeleted file mode 100644\n"
            "--- a/old.py\n+++ /dev/null\n@@ -1,3 +0,0 @@\n-a\n-b\n-c\n"
        )
        r = run(diff)
        self.assertEqual(r["reviewable"]["lines"], 3)
        self.assertEqual(r["groups"][0]["paths"], ["old.py"])


class MainTest(unittest.TestCase):
    def test_gitattributes_read_from_root(self):
        with tempfile.TemporaryDirectory() as tmp:
            env = dict(
                os.environ, GIT_CONFIG_GLOBAL="/dev/null", GIT_CONFIG_NOSYSTEM="1"
            )
            subprocess.run(["git", "init", "-q", tmp], check=True, env=env)
            Path(tmp, ".gitattributes").write_text("gen/** linguist-generated\n")
            diff_path = Path(tmp, "d.diff")
            diff_path.write_text(
                file_diff("gen/client.ts", 40) + file_diff("src/x.ts", 5)
            )
            out = io.StringIO()
            old_env = os.environ.copy()
            os.environ.update(env)
            try:
                with contextlib.redirect_stdout(out):
                    rc = size.main(["--diff", str(diff_path), "--root", tmp])
            finally:
                os.environ.clear()
                os.environ.update(old_env)
            self.assertEqual(rc, 0)
            r = json.loads(out.getvalue())
            self.assertEqual(r["reviewable"]["lines"], 5)
            self.assertEqual(r["generated"]["paths"][0]["path"], "gen/client.ts")

    def test_unreadable_diff_exits_2(self):
        with contextlib.redirect_stderr(io.StringIO()):
            self.assertEqual(
                size.main(["--diff", "/nonexistent/x.diff", "--no-attrs"]), 2
            )


if __name__ == "__main__":
    unittest.main()
